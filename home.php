                    <p class="text lh-lg">In all human endeavours (personal or professional context), risk assessment are routine standard operating procedure. However, in the context of personal health, risk assessment agenda is often side-lined and we only seek help and advice when illnesses happen. With the rapid advancement of big data technology, it has become possible to innovate non-invasive methods for self-assessment of cancer risk. This has been the impetus for us to create CARISA – a user-friendly tool in multi-language format for self-assessment of cancer risk for the five types of cancer (nasopharyngeal, colorectal, lung, breast, and cervical cancers). CARISA empowers each and every person to know their risk of getting cancers prior to seeking advice from health professionals with the aim of fostering behavioural change towards a healthier lifestyle in the community. It is part of the total and holistic approach in managing the cancer problem.</p>
